## Four years of almosts

For a long time the grassland gave me nothing but signs. A flattened scrape where she had rested. A direction a watcher had last seen her walk. And once — the hardest thing I found in all those years — a broken egg going rotten in the grass, the shell pulled apart by a fox.

That was when the full weight of it landed. A lone female, with no mate left in the grassland, will still do what her body tells her to. Each season she laid a single egg. Each season it went unfertilised, and the foxes or the sun took it. I had come to photograph a bird; I was in fact watching the quiet end of a lineage, one infertile egg at a time.

You learn a strange kind of patience in a place like that. Not the patience of waiting for good light, but the patience of returning to a story you already suspect will break your heart.

## The morning she walked into the light

It finally happened in March 2018.

We had been scanning the plain since first light, and then she was simply *there* — unhurried, head high, bill parted against the heat, walking through the dry gold as though four years were nothing at all. A particular stillness comes over you at a moment like that. You stop being a person with a camera. You hold your breath, you keep the bird in the frame, and you try not to let your hands shake.

Then the shutter. And after it, something I hadn't expected: not triumph, but a kind of ache.

