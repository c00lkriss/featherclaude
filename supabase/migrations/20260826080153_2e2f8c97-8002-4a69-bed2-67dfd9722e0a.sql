## What the photograph is really of

I don't think of this as a trophy. Four years didn't buy me a prize; they bought me an understanding. This frame may be one of the last records of a bustard on the Rollapadu grasslands — a bird photographed not at the height of her kind, but at its vanishing.

The Great Indian Bustard is running out of time, and it is running out for reasons we could still fix: grasslands lost to the plough and to "wasteland" development, and power lines strung across the last open country its heavy, low-flying body cannot dodge. Places like Rollapadu are not empty. They are among the most endangered landscapes we have — and the bird that walked through my viewfinder that morning is the reason they are worth fighting for.

I photograph birds not to collect them, but to understand them. This one taught me what that really costs — and why it matters that we reach the grasslands before the grasslands are gone.$post$
