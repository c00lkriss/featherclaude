  $post$## A grassland that keeps its secrets

Some birds you photograph. A few you court. The Great Indian Bustard I did not so much photograph as *attend* — the way you keep returning to someone you're afraid of losing.

Rollapadu is a thin sweep of open grassland in Kurnool, the kind of country India keeps quietly ploughing under. To most eyes it looks like nothing: dry grass, a few thorn trees, heat standing over the plain like water. But that openness is the whole point. The bustard is a bird of wide horizons, and Rollapadu was once among the most dependable places in the country to stand in its presence — a bird nearly a metre tall, one of the heaviest flying birds in the world, walking through gold as if it owned the light.

By the time I began going, it owned very little. Fewer than 150 Great Indian Bustards survive in the wild today, most of them in the deserts of Rajasthan. At Rollapadu, the count had come down to the loneliest number there is. One. A single female — the last of her kind in that grassland.

## The long road in

Getting there was its own ritual. Permission had to be arranged with the DFO well in advance; you did not simply drive up to Rollapadu and walk in. On the morning itself a forest beat officer would ride along with us, and we went in our own vehicles down a track that was then more rut than road — none of the facilities the sanctuary has today. Dust, a slow crawl, the light coming up pink over the grass.

I made that drive season after season, for the better part of four years.

